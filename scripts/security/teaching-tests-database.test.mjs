import test from 'node:test'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { syntheticTest, teachingTestsFixture } from './teaching-tests-fixture.mjs'

test('test definitions enforce roles, answer integrity and single immutable attempts without leaking keys', async t => {
  const fx = await teachingTestsFixture(); t.after(() => fx.close())
  const { ids, groups, db, testMutate, testList, testDetail } = fx
  const definition = syntheticTest(ids.course, [groups[0]])
  await assert.rejects(testMutate(ids.studentA, 'save_test', definition), /FORBIDDEN|UNVERIFIED/)
  await assert.rejects(testMutate(ids.owner, 'save_test', { ...definition, questions: [{ ...definition.questions[0], answer: 'unknown' }] }), /TEST_INVALID_INPUT/)
  await assert.rejects(testMutate(ids.owner, 'save_test', { ...definition, questions: [{ ...definition.questions[0], answer: undefined }] }), /TEST_INVALID_INPUT/)
  await assert.rejects(testMutate(ids.owner, 'save_test', { ...definition, targets: [{ group_id: groups[1], audience_mode: 'subgroups', subgroup_ids: [randomUUID()] }] }), /AUDIENCE_INVALID/)
  const saved = await testMutate(ids.owner, 'save_test', definition)
  assert.equal(saved.test.version, 1); assert.equal(saved.test.questions[0].answer, 'b')
  assert.equal((await testList(ids.studentA, null, groups[0])).tests.length, 1)
  assert.equal((await testList(ids.studentB, null, groups[1])).tests.length, 0)
  const before = await testDetail(ids.studentA, definition.id)
  assert.deepEqual(before.test.questions, []); assert.equal(before.attempt, null)
  const started = await testMutate(ids.studentA, 'start', { id: definition.id, group_id: groups[0] })
  assert.equal(started.attempt.current_question.id, 'choice'); assert.equal(started.attempt.current_question.answer, undefined)
  assert.equal(started.attempt.score, undefined); assert.deepEqual(started.attempts, [])
  const replay = await testMutate(ids.studentA, 'start', { id: definition.id, group_id: groups[0] })
  assert.equal(replay.attempt.id, started.attempt.id); assert.equal(replay.attempt.started_at, started.attempt.started_at)
  await assert.rejects(testMutate(ids.owner, 'save_test', { ...definition, version: 1, title: 'Changed' }), /TEST_IMMUTABLE/)
  await assert.rejects(testDetail(ids.studentB, definition.id), /TEST_FORBIDDEN/)
  await assert.rejects(fx.asUser(ids.studentA, 'select * from teaching_tests'), /permission denied/)
  await assert.rejects(fx.asUser(ids.studentA, 'select * from teaching_test_attempts'), /permission denied/)
  assert.equal((await db.query('select count(*)::int n from teaching_test_attempts')).rows[0].n, 1)
})

test('all question kinds score on server, capped bonuses become journal drafts only after teacher review', async t => {
  const fx = await teachingTestsFixture(); t.after(() => fx.close())
  const { ids, groups, db, testMutate, testDetail, rpc, mutate } = fx
  const definition = syntheticTest(ids.course, [groups[0]])
  await testMutate(ids.owner, 'save_test', definition)
  let detail = await testMutate(ids.studentA, 'start', { id: definition.id, group_id: groups[0] })
  for (let index = 0; index < definition.questions.length; index++) {
    const question = definition.questions[index]
    detail = await testMutate(ids.studentA, 'save_answer', { id: definition.id, version: detail.attempt.version, question_id: question.id, answer: question.answer })
    if (index < definition.questions.length - 1) detail = await testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: index + 1 })
    if (index === 0) assert.equal(detail.attempt.question_expires_at, null, 'disabled question timer does not inherit the total test deadline')
  }
  detail = await testMutate(ids.studentA, 'finish', { id: definition.id, version: detail.attempt.version })
  assert.equal(detail.attempt.status, 'submitted'); assert.equal(detail.attempt.score, undefined)
  assert.equal((await testDetail(ids.owner, definition.id)).attempts[0].score, 20)
  await assert.rejects(testMutate(ids.owner, 'finalize_results', { id: definition.id, version: 1 }), /TEST_RESULTS_NOT_READY/)
  await assert.rejects(testMutate(ids.owner, 'review_results', { id: definition.id, version: 1 }), /TEST_REVIEW_REQUIRED/)
  assert.equal((await db.query('select count(*)::int n from teaching_grades')).rows[0].n, 0)
  await db.query("update teaching_tests set closes_at=clock_timestamp()-interval '1 second',opens_at=clock_timestamp()-interval '1 day' where id=$1", [definition.id])
  const finalized = await testMutate(ids.owner, 'finalize_results', { id: definition.id, version: 1 })
  assert.equal(finalized.attempts[0].final_score, 20); assert.equal(finalized.attempts[0].bonus_score, 0)
  assert.equal((await testMutate(ids.owner, 'finalize_results', { id: definition.id, version: 1 })).test.version, finalized.test.version)
  const reviewed = await testMutate(ids.owner, 'review_results', { id: definition.id, version: finalized.test.version })
  assert.ok(reviewed.attempts[0].reviewed_at)
  const grade = (await db.query('select * from teaching_grades')).rows[0]
  assert.equal(grade.draft_score, '20.00'); assert.equal(grade.published_score, null)
  assert.equal((await rpc(ids.studentA, 'xelay_teaching_group', [groups[0]])).grades.length, 0)
  const auditBefore = (await db.query('select count(*)::int n from teaching_grade_audit')).rows[0].n
  await testMutate(ids.owner, 'review_results', { id: definition.id, version: finalized.test.version })
  assert.equal((await db.query('select count(*)::int n from teaching_grade_audit')).rows[0].n, auditBefore)
  const afterEdit = await mutate(ids.owner, 'save_grade', { activity_id: grade.activity_id, entry_id: grade.entry_id, version: grade.version, score: 18, comment: 'Перевірено', reason: '' })
  await mutate(ids.owner, 'publish_grades', { activity_id: grade.activity_id, expected_versions: [{ entry_id: grade.entry_id, version: afterEdit.version }] })
  const student = await testDetail(ids.studentA, definition.id)
  assert.equal(student.attempt.published_score, 18); assert.equal(student.attempt.score, undefined)
  assert.equal((await rpc(ids.studentB, 'xelay_teaching_group', [groups[1]])).grades.length, 0)
})

test('server validates partial answers, question clocks, navigation rules and stale save attempts', async t => {
  const fx = await teachingTestsFixture(); t.after(() => fx.close())
  const { ids, groups, db, testMutate, testDetail } = fx
  const definition = syntheticTest(ids.course, [groups[0]], { allow_skip: false, allow_return: false, question_timer_policy: 'lock_on_leave' })
  await testMutate(ids.owner, 'save_test', definition)
  let detail = await testMutate(ids.studentA, 'start', { id: definition.id, group_id: groups[0] })
  await assert.rejects(testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: 1 }), /TEST_NAVIGATION_BLOCKED/)
  await assert.rejects(testMutate(ids.studentA, 'save_answer', { id: definition.id, version: detail.attempt.version, question_id: 'choice', answer: 'invalid' }), /TEST_INVALID_INPUT/)
  const firstVersion = detail.attempt.version
  detail = await testMutate(ids.studentA, 'save_answer', { id: definition.id, version: firstVersion, question_id: 'choice', answer: 'a' })
  await assert.rejects(testMutate(ids.studentA, 'save_answer', { id: definition.id, version: firstVersion, question_id: 'choice', answer: 'b' }), /TEST_CONFLICT/)
  await db.query("update teaching_test_attempts set opened_at=jsonb_set(opened_at,'{choice}',to_jsonb(clock_timestamp()-interval '31 seconds')) where id=$1", [detail.attempt.id])
  await assert.rejects(testMutate(ids.studentA, 'save_answer', { id: definition.id, version: detail.attempt.version, question_id: 'choice', answer: 'b' }), /TEST_ANSWER_LOCKED/)
  detail = await testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: 1 })
  assert.ok(detail.attempt.locked.includes('choice'))
  await assert.rejects(testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: 0 }), /TEST_NAVIGATION_BLOCKED/)
  await db.query("update teaching_test_attempts set expires_at=clock_timestamp()-interval '1 second' where id=$1", [detail.attempt.id])
  const teacherExpired = await testDetail(ids.owner, definition.id)
  assert.equal(teacherExpired.attempts[0].status, 'submitted', 'teacher detail finishes expired attempts even while the overall test is open')
  assert.equal(new Date(teacherExpired.attempts[0].submitted_at).getTime(), new Date(teacherExpired.attempts[0].expires_at).getTime(), 'completion keeps the original server deadline')
  assert.ok(new Date(teacherExpired.test.closes_at) > new Date(teacherExpired.server_now))
  const expired = await testDetail(ids.studentA, definition.id)
  assert.equal(expired.attempt.status, 'submitted'); assert.equal(expired.attempt.current_question, null)
  assert.equal((await testMutate(ids.studentA, 'start', { id: definition.id, group_id: groups[0] })).attempt.id, expired.attempt.id)
  const submittedAgain = await testMutate(ids.studentA, 'save_answer', { id: definition.id, version: 9999, question_id: 'choice', answer: 'b' })
  assert.equal(submittedAgain.attempt.status, 'submitted')
  assert.equal((await testDetail(ids.owner, definition.id)).attempts[0].score, 0)
})

test('partial credit and competition order prioritize correctness then time and never cross the configured maximum', async t => {
  const fx = await teachingTestsFixture(); t.after(() => fx.close())
  const { ids, groups, db, testMutate, testDetail } = fx
  const definition = syntheticTest(ids.course, [groups[0]], { bonus_percent: 20 })
  await testMutate(ids.owner, 'save_test', definition)
  let detail = await testMutate(ids.studentA, 'start', { id: definition.id, group_id: groups[0] })
  detail = await testMutate(ids.studentA, 'save_answer', { id: definition.id, version: detail.attempt.version, question_id: 'choice', answer: 'b' })
  detail = await testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: 1 })
  detail = await testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: 2 })
  detail = await testMutate(ids.studentA, 'save_answer', { id: definition.id, version: detail.attempt.version, question_id: 'sorting', answer: { two: 'even', three: 'even' } })
  detail = await testMutate(ids.studentA, 'navigate', { id: definition.id, version: detail.attempt.version, index: 3 })
  detail = await testMutate(ids.studentA, 'save_answer', { id: definition.id, version: detail.attempt.version, question_id: 'sequence', answer: ['one', 'three', 'two'] })
  await testMutate(ids.studentA, 'finish', { id: definition.id, version: detail.attempt.version })
  const teacher = await testDetail(ids.owner, definition.id)
  assert.equal(teacher.attempts[0].score, 9.17)
  const headAttempt = await testMutate(ids.headA, 'start', { id: definition.id, group_id: groups[0] })
  await testMutate(ids.headA, 'finish', { id: definition.id, version: headAttempt.attempt.version })
  await db.query("update teaching_tests set closes_at=clock_timestamp()-interval '1 second',opens_at=clock_timestamp()-interval '1 day' where id=$1", [definition.id])
  const finalized = await testMutate(ids.owner, 'finalize_results', { id: definition.id, version: 1 })
  const student = finalized.attempts.find(a => a.user_id === ids.studentA)
  assert.equal(student.bonus_score, 2); assert.equal(student.final_score, 11.17)
  assert.equal(finalized.attempts.find(a => a.user_id === ids.headA).bonus_score, 0)
})
